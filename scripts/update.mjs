export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const REPO = 'kelsilib/Shadowrocket';
export const BRANCH = 'custom';
export const RAW = `https://raw.githubusercontent.com/${REPO}/${BRANCH}`;
export const LOW_RATE_REGEX = '实验|(^|[^0-9.])0\\.[16][xX](?![A-Za-z0-9])';
export const SOURCES = {
  'lazy_group.conf': 'https://raw.githubusercontent.com/LOWERTOP/Shadowrocket/main/lazy_group.conf',
  'AI.txt': 'https://raw.githubusercontent.com/iab0x00/ProxyRules/main/Rule/AI.txt',
  'gemini.list': 'https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/Gemini/Gemini.list',
  'appletv.list': 'https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/AppleTV/AppleTV.list',
  'xiaohongshu.list': 'https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/XiaoHongShu/XiaoHongShu.list',
};

const GOOGLE_ROOTS = ['google.com', 'googleapis.com', 'gstatic.com', 'googleusercontent.com',
  'googlezip.net', 'googletagmanager.com', 'google.dev', 'google', 'goog', 'deepmind.com'];
const RULE_TYPES = new Set(['DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD', 'DOMAIN-WILDCARD', 'USER-AGENT']);

export function rules(text) {
  return text.split(/\r?\n/).map(x => x.trim()).filter(x => x && !x.startsWith('#'));
}

function validateList(text, label) {
  const entries = rules(text);
  if (!entries.length) throw new Error(`${label}: empty rule list`);
  for (const entry of entries) {
    const [type, value, ...extra] = entry.split(',');
    if (!RULE_TYPES.has(type) || !value || extra.length) {
      throw new Error(`${label}: unsupported rule, review upstream changes: ${entry}`);
    }
  }
}

export function isGoogleRule(line) {
  const [, value = ''] = line.split(',');
  const domain = value.toLowerCase().replace(/^\*\./, '');
  return GOOGLE_ROOTS.some(root => domain === root || domain.endsWith(`.${root}`))
    || /(?:^|[.])(?:google|googleapis|gstatic)(?:[.]|$)/.test(domain);
}

export function splitAI(text) {
  const ai = [], google = [];
  let googleSection = false;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    // Top-level headings have exactly one >; preserve nested Google service sections.
    const heading = /^#\s*>\s*(?!>)(.+)$/.exec(line);
    if (heading) googleSection = /google|gemini/i.test(heading[1]);
    if (!line || line.startsWith('#')) continue;
    (googleSection || isGoogleRule(line) ? google : ai).push(line);
  }
  if (!ai.length || !google.length) throw new Error('AI split failed; review upstream format');
  return { ai, google };
}

// Remove exact duplicates and DOMAIN entries already covered by a suffix in the same list.
export function compact(entries) {
  const unique = [...new Set(entries)];
  const suffixes = unique.filter(x => x.startsWith('DOMAIN-SUFFIX,')).map(x => x.split(',')[1]);
  return unique.filter(line => {
    const [type, value] = line.split(',');
    if (type !== 'DOMAIN' && type !== 'DOMAIN-SUFFIX') return true;
    return !suffixes.some(suffix => value.endsWith(`.${suffix}`) || (type === 'DOMAIN' && value === suffix));
  });
}

function listFile(title, entries, sources) {
  return [`# ${title}`, '# Generated by scripts/update.mjs; edit sources or overrides instead.',
    '# Custom adaptation: kelsilib, 2026-11-14. Upstream authors and terms retained.',
    ...(sources.some(x => x.includes('blackmatrix7')) ? ['# blackmatrix7 source terms: GPL-2.0; see licenses/blackmatrix7-GPL-2.0.txt.'] : []),
    ...sources.map(x => `# Source: ${x}`), `# Rules: ${entries.length}`, ...entries, ''].join('\n');
}

function once(text, before, after) {
  if (text.split(before).length !== 2) throw new Error(`Upstream anchor changed: ${before}`);
  return text.replace(before, after);
}

export function makeConfig(original) {
  let text = original.replace(/\r\n/g, '\n');
  text = `# kelsilib 定制：Apple TV / Google AI 拆分 / 低倍率手选 / 小红书与 rednote 直连\n# 基于 LOWERTOP/Shadowrocket 的 lazy_group.conf，使用 scripts/update.mjs 更新。\n` + text;
  text = once(text, '[General]\n', `[General]\nupdate-url = ${RAW}/lazy_group.conf\n`);
  text = once(text, 'dns-direct-fallback-proxy = true', 'dns-direct-fallback-proxy = false');
  const groupStart = text.indexOf('[Proxy Group]');
  const ruleStart = text.indexOf('[Rule]');
  if (groupStart < 0 || ruleStart < groupStart) throw new Error('Missing config sections');
  let groups = text.slice(groupStart, ruleStart).split('\n').map(line => {
    if (!line.startsWith('#') && /^.+ = select,/.test(line)) {
      return line.replace('PROXY,', 'PROXY,低倍率节点,');
    }
    return line;
  }).join('\n');
  const appleTV = 'Apple TV = select,PROXY,低倍率节点,香港节点,台湾节点,日本节点,新加坡节点,韩国节点,美国节点,policy-select-name=PROXY';
  const lowRate = `低倍率节点 = select,policy-regex-filter=${LOW_RATE_REGEX}`;
  groups = once(groups, 'AI = select,', `${appleTV}\n# 名称包含 实验 / 0.1x / 0.6x 的节点，手动选择，不自动测速切换。\n${lowRate}\nAI = select,`);
  text = text.slice(0, groupStart) + groups + text.slice(ruleStart);
  const aiStart = text.indexOf('\n# AI\n', text.indexOf('[Rule]'));
  const aiEndMarker = 'RULE-SET,https://raw.githubusercontent.com/iab0x00/ProxyRules/main/Rule/AI.txt,AI';
  const aiEnd = text.indexOf(aiEndMarker, aiStart);
  if (aiStart < 0 || aiEnd < 0) throw new Error('Upstream AI block changed');
  const customRules = [
    '', '# 小红书 / rednote：显式直连放在全部通用服务规则之前。',
    `RULE-SET,${RAW}/rules/XiaoHongShu_Direct.list,DIRECT`,
    '', '# Apple TV / TV+：先于通用苹果服务。',
    `RULE-SET,${RAW}/rules/AppleTV.list,Apple TV`,
    '', '# Google AI 已从 AI 总表中移出，仅交给谷歌服务。',
    `RULE-SET,${RAW}/rules/GoogleAI.list,谷歌服务`,
    `RULE-SET,${RAW}/rules/AI_NoGoogle.list,AI`,
  ].join('\n');
  text = text.slice(0, aiStart) + customRules + text.slice(aiEnd + aiEndMarker.length);
  text = once(text, 'RULE-SET,https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/XiaoHongShu/XiaoHongShu.list,DIRECT\n', '');
  // Resolve service references to their exact declared names, including case.
  const names = new Map();
  for (const line of groups.split('\n')) {
    if (line && !line.startsWith('#') && line.includes(' = ')) {
      const name = line.split(' = ')[0];
      names.set(name.toUpperCase(), name);
    }
  }
  let section = '';
  text = text.split('\n').map(line => {
    if (line.startsWith('[')) section = line;
    if (section !== '[Rule]' || !line || line.startsWith('#') || line.startsWith('[')) return line;
    const fields = line.split(',');
    const policyIndex = /^(FINAL|MATCH)$/.test(fields[0]) ? 1 : 2;
    if (names.has(fields[policyIndex]?.toUpperCase())) fields[policyIndex] = names.get(fields[policyIndex].toUpperCase());
    return fields.join(',');
  }).join('\n');
  return text;
}

export async function build({ offline = false } = {}) {
  const sources = {};
  if (offline) {
    for (const name of Object.keys(SOURCES)) sources[name] = await readFile(resolve(ROOT, 'sources', name), 'utf8');
  } else {
    // Fetch all inputs before changing published outputs. A failed download aborts the build.
    await Promise.all(Object.entries(SOURCES).map(async ([name, url]) => {
      const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
      sources[name] = (await response.text()).replace(/^\uFEFF/, '');
    }));
  }
  for (const [name, content] of Object.entries(sources)) {
    if (name !== 'lazy_group.conf') validateList(content, name);
    else if (!content.includes('[Rule]')) throw new Error('Invalid original config');
  }
  const { ai, google } = splitAI(sources['AI.txt']);
  const override = await readFile(resolve(ROOT, 'overrides/xiaohongshu.list'), 'utf8');
  validateList(override, 'xiaohongshu overrides');
  const googleRules = compact([...google, ...rules(sources['gemini.list'])]);
  const outputs = {
    'lazy_group.conf': makeConfig(sources['lazy_group.conf']),
    'rules/AI_NoGoogle.list': listFile('AI excluding Google AI', compact(ai), [SOURCES['AI.txt']]),
    'rules/GoogleAI.list': listFile('Google AI (Gemini / AI Studio / NotebookLM / related services)', googleRules, [SOURCES['AI.txt'], SOURCES['gemini.list']]),
    'rules/AppleTV.list': listFile('Apple TV / TV+', compact(rules(sources['appletv.list'])), [SOURCES['appletv.list']]),
    'rules/XiaoHongShu_Direct.list': listFile('Xiaohongshu / rednote / media CDN / share links', compact([...rules(sources['xiaohongshu.list']), ...rules(override)]), [SOURCES['xiaohongshu.list'], 'overrides/xiaohongshu.list']),
  };
  if (rules(outputs['rules/AI_NoGoogle.list']).some(isGoogleRule)) throw new Error('Google rule leaked into AI');
  const manifest = Object.fromEntries(Object.entries(SOURCES).map(([name, url]) => [name, {
    url, sha256: createHash('sha256').update(sources[name]).digest('hex'),
  }]));
  outputs['sources/manifest.json'] = JSON.stringify(manifest, null, 2) + '\n';
  // Regression checks run on staged output before any source/output is replaced.
  const { check } = await import('./check.mjs');
  check(outputs, sources);
  for (const [name, content] of Object.entries(sources)) outputs[`sources/${name}`] = content;
  for (const [name, content] of Object.entries(outputs)) {
    const target = resolve(ROOT, name);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(`${target}.tmp`, content, 'utf8');
    await rename(`${target}.tmp`, target);
  }
  console.log(`Generated: AI ${compact(ai).length}, Google AI ${googleRules.length}, Apple TV ${rules(outputs['rules/AppleTV.list']).length}, Xiaohongshu ${rules(outputs['rules/XiaoHongShu_Direct.list']).length}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  build({ offline: process.argv.includes('--offline') }).catch(error => {
    console.error(error);
    process.exitCode = 1;
  });
}
